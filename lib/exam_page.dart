      "question_text": "When making an HTTP GET request that returns a large JSON array, what is the best way to parse this in Dart to avoid UI thread blocking?",
      "options": {
        "A": "Parse it synchronously on the main thread.",
        "B": "Use the compute() function to parse it in a background isolate.",

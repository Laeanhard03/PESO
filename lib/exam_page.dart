import 'dart:async';

import 'package:flutter/material.dart';

class AIExamPage extends StatefulWidget {
  final String jobTitle;
  final String company;

  const AIExamPage({super.key, required this.jobTitle, required this.company});

  @override
  State<AIExamPage> createState() => _AIExamPageState();
}

class _AIExamPageState extends State<AIExamPage> {
  final Color pesoGreen = const Color(0xFF2E7D32);

  // State variables
  int _currentIndex = 0;
  final Map<int, String> _selectedAnswers =
      {}; // Tracks selected option (A, B, C, D)

  // Timer variables
  late Timer _timer;
  int _timeLeftInSeconds = 15 * 60; // 15 Minutes for the 5-question exam

  // --- MOCK DATABASE: AI GENERATED JSON EXAM ---
  // This simulates the exact JSON schema generated by Prompt 1
  final List<Map<String, dynamic>> _mockExamData = [
    {
      "question_id": "q1",
      "difficulty": "Intermediate",
      "skill_tested": "System Architecture",
      "type": "Technical",
      "question_text": "Which architectural pattern is most suited for maintaining highly scalable, decoupled Flutter applications?",
      "options": {
        "A": "MVC (Model-View-Controller)",
        "B": "BLoC / Clean Architecture",
        "C": "Standard StatefulWidget setState()",
        "D": "Singletons for all data management",
      },
      "correct_answer": "B",
    },
    {
      "question_id": "q2",
      "difficulty": "Beginner",
      "skill_tested": "Problem Solving",
      "type": "General Aptitude",
      "question_text": "If a critical server goes down during a peak traffic hour, what is the most appropriate first step in a professional environment?",
      "options": {
        "A": "Immediately rewrite the server code.",
        "B": "Wait for a manager to notice and give instructions.",
        "C": "Communicate the outage to stakeholders and check error logs.",
        "D": "Restart the database without saving states.",
      },
      "correct_answer": "C",
    },
    {
      "question_id": "q3",
      "difficulty": "Intermediate",
      "skill_tested": "API Integration",
